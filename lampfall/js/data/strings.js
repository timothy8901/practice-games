/**
 * Looks a key up and fills its placeholders.
 * @param {string} key
 * @param {Record<string, any>} [vars]
 * @returns {string} the filled template, or `[key]` when the key is unknown
 */
export function t(key, vars = {}) {
  const tpl = STRINGS[key];
  if (tpl === undefined) return `[${key}]`;
  return fill(tpl, vars);
}

/**
 * Whether a key exists.
 * @param {string} key
 * @returns {boolean}
 */
export function has(key) {
  return Object.prototype.hasOwnProperty.call(STRINGS, key);
}

/**
 * Fills `{name}` and `{name|one|many}` placeholders in any template string. Unknown names are left
 * as written so a missing variable is visible.
 * @param {string} tpl
 * @param {Record<string, any>} [vars]
 * @returns {string}
 */
export function fill(tpl, vars = {}) {
  return String(tpl).replace(/\{([a-zA-Z0-9_.:-]+)(?:\|([^|}]*)\|([^}]*))?\}/g, (m, name, one, many) => {
    if (!Object.prototype.hasOwnProperty.call(vars, name)) return m;
    const v = vars[name];
    if (one !== undefined) return Number(v) === 1 ? one : many;
    return v === null || v === undefined ? '' : String(v);
  });
}

const NUMBER_WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve'];

/**
 * A small count as a word ('one creature'), digits past twelve.
 * @param {number} n
 * @param {boolean} [cap]  capitalise the first letter (sentence start)
 * @returns {string}
 */
export function numberWord(n, cap = false) {
  const w = Number.isInteger(n) && n >= 0 && n < NUMBER_WORDS.length ? NUMBER_WORDS[n] : String(n);
  return cap ? w.charAt(0).toUpperCase() + w.slice(1) : w;
}

/**
 * Picks a singular or plural word.
 * @param {number} n
 * @param {string} one
 * @param {string} many
 * @returns {string}
 */
export function plural(n, one, many) {
  return n === 1 ? one : many;
}

/**
 * Placeholder names a template uses (plural forms included), in order of first use.
 * @param {string} tpl
 * @returns {string[]}
 */
export function varsOf(tpl) {
  const out = [];
  for (const m of String(tpl).matchAll(/\{([a-zA-Z0-9_.:-]+)(?:\|[^|}]*\|[^}]*)?\}/g)) if (!out.includes(m[1])) out.push(m[1]);
  return out;
}

/**
 * Builds the options of a {@link CONFIRMS} entry for `ui/confirm` (safe option first, focused).
 * @param {string} id   a CONFIRMS key
 * @param {Record<string, any>} [vars]
 * @returns {{body: string, options: string[], defaultIndex: 0, danger: boolean}}
 */
export function confirmSpec(id, vars = {}) {
  const c = CONFIRMS[id];
  if (!c) return { body: `[confirm:${id}]`, options: [t('confirm.no'), t('confirm.yes')], defaultIndex: 0, danger: false };
  return { body: t(c.body, vars), options: c.options.map((k) => t(k, vars)), defaultIndex: 0, danger: Boolean(c.danger) };
}
